   })

(defn table [& {:keys [input-path pipeline-fn dataset-name parser-fn key-fn]
                :or {input-path input-path
                     dataset-name dataset-name
                     parser-fn parser-map
                     key-fn keyword}
                :as _opts}]
  (-> input-path
      (tc/dataset 
       {:dataset-name dataset-name
        :key-fn key-fn
        :parser-fn parser-fn})
      (cond-> pipeline-fn pipeline-fn)))

(defn format-financial-year [fy-int]
  (let [[_ y1 y2] (re-find #"([0-9]{4})([0-9]{2})" (str fy-int))]
    (format "FY %s/%s" y1 y2)))

(def geocode-columns [:country_code :region_code :old_la_code :new_la_code])
(defn tidy-geocodes [ds]
  (-> ds
      (tc/map-columns :geo-code geocode-columns (fn [c r _o l] (or l r c)))
      (tc/drop-columns geocode-columns)))

(def geoname-columns [:country_name :region_name :la_name])
(defn tidy-geonames [ds]
  (-> ds
      (tc/map-columns :geo-name geoname-columns (fn [c r l] (or l r c)))
      (tc/drop-columns geoname-columns)))

(def gather-columns 
  [:early_years_establishments :primary_schools :secondary_schools :post_16
   :pupil_referral_units_and_alt_provision :sen_and_special_schools
   :gross_expenditure :income :net_expenditure :net_per_capita_expenditure])

(defn tidy-table
  ([dataset]
   (-> dataset
       tidy-geocodes
       tidy-geonames
       (tc/drop-columns [:EES_order])
       (tc/pivot->longer gather-columns {:value-column-name :amount
                                         :target-columns :setting})))
  ([]
   (-> (table)
       (tidy-table))))

